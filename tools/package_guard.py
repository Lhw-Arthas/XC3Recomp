"""Packaging guard (Constitution art. I, SC-012): fails if a tree to be published holds game or derived files.

Usage: package_guard.py <dir> [<dir> ...] | --git <repo>   (exit 0 = clean, 1 = violations)
Checks: forbidden extensions, NSO magic, key files/content, forbidden directory names, and lifted C code.
"""
import os
import re
import sys

FORBIDDEN_EXT = ('.nsp', '.xci', '.nca', '.nsz', '.xcz', '.nso', '.nro', '.bfttf', '.bfotf')
FORBIDDEN_DIRS = {'targets', 'generated', 'extracted', 'romfs', 'exefs'}
SKIP_DIRS = {'.git', '.venv', '__pycache__', 'node_modules'}
KEY_NAMES = {'prod.keys', 'title.keys', 'dev.keys', 'title.keys_autogenerated'}
KEY_RE = re.compile(rb'(master_key|titlekek|key_area_key|aes_kek_generation)[a-z_0-9]*\s*=\s*[0-9a-fA-F]{32}')
LIFTED_RE = re.compile(rb'void f_[0-9a-f]{6,}\(Cpu \*c\)')
TEXT_SCAN_MAX = 8 * 1024 * 1024


def scan(root):
    out = []
    for dirpath, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for d in dirs:
            if d.lower() in FORBIDDEN_DIRS:
                out.append(f'forbidden directory: {os.path.relpath(os.path.join(dirpath, d), root)}')
        for f in files:
            p = os.path.join(dirpath, f)
            rel = os.path.relpath(p, root)
            low = f.lower()
            if low.endswith(FORBIDDEN_EXT):
                out.append(f'forbidden extension {os.path.splitext(low)[1]}: {rel}')
                continue
            if low in KEY_NAMES:
                out.append(f'key file: {rel}')
                continue
            try:
                size = os.path.getsize(p)
                with open(p, 'rb') as fh:
                    head = fh.read(min(size, TEXT_SCAN_MAX))
            except OSError:
                continue
            if head[:4] == b'NSO0':
                out.append(f'NSO binary (by magic): {rel}')
            elif KEY_RE.search(head):
                out.append(f'key material in file: {rel}')
            elif low.endswith(('.c', '.h', '.inc')) and LIFTED_RE.search(head):
                out.append(f'lifted game code: {rel}')
    return out


def scan_tracked(repo):
    """Same checks over the files git tracks (what would be published), not the whole working tree."""
    import subprocess
    names = subprocess.run(['git', '-C', repo, 'ls-files', '-z', '--recurse-submodules'], capture_output=True,
                           check=True).stdout.decode('utf-8', 'replace').split(chr(0))
    out = []
    for n in filter(None, names):
        p = os.path.join(repo, n)
        if not os.path.isfile(p):
            continue
        low = n.lower()
        base = os.path.basename(low)
        if low.endswith(FORBIDDEN_EXT):
            out.append(f'forbidden extension: {n}')
        elif base in KEY_NAMES:
            out.append(f'key file: {n}')
        else:
            with open(p, 'rb') as fh:
                head = fh.read(TEXT_SCAN_MAX)
            if head[:4] == b'NSO0':
                out.append(f'NSO binary (by magic): {n}')
            elif KEY_RE.search(head):
                out.append(f'key material in file: {n}')
            elif low.endswith(('.c', '.h', '.inc')) and LIFTED_RE.search(head):
                out.append(f'lifted game code: {n}')
    return out


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if not argv:
        print(__doc__)
        return 1
    bad = []
    if argv[0] == '--git':
        bad += scan_tracked(argv[1] if len(argv) > 1 else '.')
    else:
        for root in argv:
            bad += scan(root)
    for v in bad:
        print('VIOLATION:', v)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
