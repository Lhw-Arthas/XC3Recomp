"""Coverage report + function map for generated modules (T014, T015).

Reads generated/<module>.log (stats line printed by gen.py) and generated/<module>/<module>_table.c, and the NSO's
symbols. Writes docs/evidence/<out>/coverage.md and build/maps/<module>.csv (address,size,name).
Only counts and addresses are written to docs/ (Constitution art. I).
"""
import argparse
import ast
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
sys.path.insert(0, os.path.join(ROOT, 'tools', 'lifter'))


def parse_log(path):
    txt = open(path, encoding='utf-8', errors='replace').read()
    m = re.search(r'(\w+): (\d+) boundaries, (\d+) functions, (\d+) rounds, (\{.*?\}), (\d+)s', txt)
    if not m:
        return None
    return {'boundaries': int(m[2]), 'functions': int(m[3]), 'rounds': int(m[4]),
            'stats': ast.literal_eval(m[5]), 'seconds': int(m[6])}


def fn_addrs(table_c):
    txt = open(table_c, encoding='utf-8').read()
    body = re.search(r'_fn_addrs\[\] = \{(.*?)\};', txt, re.S).group(1)
    return [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', body)]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--profile', default=os.path.join(ROOT, 'games', 'xcde', 'profile.json'))
    ap.add_argument('--exefs', default=os.path.join(ROOT, 'targets', 'exefs'))
    ap.add_argument('--gen', default=os.path.join(ROOT, 'generated'))
    ap.add_argument('--evidence', default=os.path.join(ROOT, 'docs', 'evidence', 'M1'))
    ap.add_argument('--maps', default=os.path.join(ROOT, 'build', 'maps'))
    a = ap.parse_args(argv)
    from nso import Nso
    prof = json.load(open(a.profile, encoding='utf-8'))
    os.makedirs(a.evidence, exist_ok=True)
    os.makedirs(a.maps, exist_ok=True)
    rows = []
    for m in prof['modules']:
        if not m['lift']:
            continue
        name, base = m['name'], int(m['base'], 16)
        st = parse_log(os.path.join(a.gen, name + '.log'))
        if st is None:
            print(f'{name}: no stats in log', file=sys.stderr)
            return 1
        addrs = sorted(fn_addrs(os.path.join(a.gen, name, name + '_table.c')))
        nso = Nso(os.path.join(a.exefs, name))
        text_end = base + nso.text[0] + nso.text[1]
        syms = {base + v: n for n, info, shndx, v, size in nso.syms if shndx and (info & 0xF) == 2}
        with open(os.path.join(a.maps, name + '.csv'), 'w', encoding='utf-8') as f:
            f.write('address,size,name\n')
            for i, ad in enumerate(addrs):
                end = addrs[i + 1] if i + 1 < len(addrs) else text_end
                f.write(f'{ad:#x},{end - ad},{syms.get(ad, "")}\n')
        s = st['stats']
        jt, allb, disp = s.get('jumptables', 0), s.get('br_all_labels', 0), s.get('br_dispatch', 0)
        tables_total = jt + allb
        rows.append((name, st, len(addrs), sum(1 for ad in addrs if ad in syms), jt, allb, disp,
                     s.get('unsupported', 0), nso.text[1]))
    with open(os.path.join(a.evidence, 'coverage.md'), 'w', encoding='utf-8') as f:
        f.write('# Generator coverage (M1)\n\n')
        f.write('Generated by `tools/report.py`. Counts and addresses only.\n\n')
        f.write('| Module | `.text` (B) | Functions | with a symbol | Tables resolved | Tables unresolved (fallback) | `br` by dispatch | Unsupported | Gen. time |\n')
        f.write('|---|---|---|---|---|---|---|---|---|\n')
        for name, st, nf, nsym, jt, allb, disp, uns, tsz in rows:
            pct = f'{100 * jt / (jt + allb):.1f} %' if jt + allb else 'n/a'
            f.write(f'| {name} | {tsz:,} | {nf:,} | {nsym:,} | {jt} ({pct}) | {allb} | {disp:,} | {uns} | {st["seconds"]} s |\n')
        f.write('\n"Unsupported" = instructions the lifter can\'t translate (an `Unsupported` trap). '
                '"Tables unresolved" use the all-labels-of-the-function fallback (research R4).\n')
    print(open(os.path.join(a.evidence, 'coverage.md'), encoding='utf-8').read())
    return 0


if __name__ == '__main__':
    sys.exit(main())
